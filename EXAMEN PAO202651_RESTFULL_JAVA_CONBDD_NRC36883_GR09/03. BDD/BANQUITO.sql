-- Base de datos del sistema CORE del Banco BanQuito con el módulo de crédito.
-- Motor: MariaDB / MySQL. Ejecutar como root:
--   mysql -u root -p < BANQUITO.sql
-- Las fechas de los movimientos son relativas a CURDATE() para que las reglas de
-- "último mes" y "últimos 3 meses" se cumplan el día en que se ejecute el script.

DROP DATABASE IF EXISTS banquito;
CREATE DATABASE banquito CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE USER IF NOT EXISTS 'banquito'@'localhost' IDENTIFIED BY 'banquito';
GRANT ALL PRIVILEGES ON banquito.* TO 'banquito'@'localhost';
FLUSH PRIVILEGES;
USE banquito;

-- Modelo del CORE entregado en el enunciado
CREATE TABLE CLIENTE (
    COD_CLIENTE      INT          NOT NULL AUTO_INCREMENT,
    CEDULA           VARCHAR(100) NOT NULL,
    NOMBRE           VARCHAR(100) NOT NULL,
    GENERO           VARCHAR(1)   NOT NULL,
    FECHA_NACIMIENTO DATE         NOT NULL,
    CONSTRAINT PK_CLIENTE PRIMARY KEY (COD_CLIENTE),
    CONSTRAINT UK_CLIENTE_CEDULA UNIQUE (CEDULA),
    CONSTRAINT CK_CLIENTE_GENERO CHECK (GENERO IN ('M', 'F'))
);

CREATE TABLE CUENTA (
    NUM_CUENTA  VARCHAR(8)    NOT NULL,
    COD_CLIENTE INT           NOT NULL,
    SALDO       NUMERIC(10,2) NOT NULL DEFAULT 0,
    CONSTRAINT PK_CUENTA PRIMARY KEY (NUM_CUENTA),
    CONSTRAINT FK_CUENTA_CLIENTE FOREIGN KEY (COD_CLIENTE) REFERENCES CLIENTE (COD_CLIENTE)
);

CREATE TABLE MOVIMIENTO (
    COD_MOVIMIENTO INT           NOT NULL AUTO_INCREMENT,
    NUM_CUENTA     VARCHAR(8)    NOT NULL,
    TIPO           VARCHAR(3)    NOT NULL,
    VALOR          NUMERIC(10,2) NOT NULL,
    FECHA          DATE          NOT NULL,
    CONSTRAINT PK_MOVIMIENTO PRIMARY KEY (COD_MOVIMIENTO),
    CONSTRAINT FK_MOVIMIENTO_CUENTA FOREIGN KEY (NUM_CUENTA) REFERENCES CUENTA (NUM_CUENTA),
    CONSTRAINT CK_MOVIMIENTO_TIPO CHECK (TIPO IN ('DEP', 'RET')),
    CONSTRAINT CK_MOVIMIENTO_VALOR CHECK (VALOR > 0)
);

-- Módulo de crédito: datos del crédito y su tabla de amortización
CREATE TABLE CREDITO (
    COD_CREDITO   INT           NOT NULL AUTO_INCREMENT,
    COD_CLIENTE   INT           NOT NULL,
    MONTO         NUMERIC(10,2) NOT NULL,
    NUMERO_CUOTAS INT           NOT NULL,
    TASA_ANUAL    NUMERIC(5,2)  NOT NULL,
    VALOR_CUOTA   NUMERIC(10,2) NOT NULL,
    FECHA         DATE          NOT NULL,
    ESTADO        VARCHAR(10)   NOT NULL DEFAULT 'ACTIVO',
    CONSTRAINT PK_CREDITO PRIMARY KEY (COD_CREDITO),
    CONSTRAINT FK_CREDITO_CLIENTE FOREIGN KEY (COD_CLIENTE) REFERENCES CLIENTE (COD_CLIENTE),
    CONSTRAINT CK_CREDITO_CUOTAS CHECK (NUMERO_CUOTAS BETWEEN 3 AND 18),
    CONSTRAINT CK_CREDITO_ESTADO CHECK (ESTADO IN ('ACTIVO', 'CANCELADO'))
);

CREATE TABLE TABLA_AMORTIZACION (
    COD_CREDITO    INT           NOT NULL,
    NUMERO_CUOTA   INT           NOT NULL,
    VALOR_CUOTA    NUMERIC(10,2) NOT NULL,
    INTERES_PAGADO NUMERIC(10,2) NOT NULL,
    CAPITAL_PAGADO NUMERIC(10,2) NOT NULL,
    SALDO          NUMERIC(10,2) NOT NULL,
    CONSTRAINT PK_TABLA_AMORTIZACION PRIMARY KEY (COD_CREDITO, NUMERO_CUOTA),
    CONSTRAINT FK_AMORTIZACION_CREDITO FOREIGN KEY (COD_CREDITO) REFERENCES CREDITO (COD_CREDITO)
);

